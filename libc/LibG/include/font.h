#ifndef LIBG_FONT_H
#define LIBG_FONT_H

#include <stdint.h>

#define LIBG_FONT_WIDTH		5
#define LIBG_FONT_HEIGHT	7
#define LIBG_FONT_ADVANCE	6

#define LIBG_FONT_PICK(r, a, b, c, d, e, f, g) \
	((r) == 0 ? (a) : (r) == 1 ? (b) : (r) == 2 ? (c) : \
	(r) == 3 ? (d) : (r) == 4 ? (e) : (r) == 5 ? (f) : (g))

static inline uint8_t
libg_font_row(uint32_t ch, uint32_t row)
{
	if (row >= LIBG_FONT_HEIGHT) {
		return (0);
	}
	if (ch >= 'a' && ch <= 'z') {
		ch -= ('a' - 'A');
	}

	switch (ch) {
	case ' ':
		return (0x00);
	case '!':
		return (LIBG_FONT_PICK(row, 0x04, 0x04, 0x04, 0x04, 0x04,
		    0x00, 0x04));
	case '"':
		return (LIBG_FONT_PICK(row, 0x0a, 0x0a, 0x0a, 0x00, 0x00,
		    0x00, 0x00));
	case '#':
		return (LIBG_FONT_PICK(row, 0x0a, 0x0a, 0x1f, 0x0a, 0x1f,
		    0x0a, 0x0a));
	case '$':
		return (LIBG_FONT_PICK(row, 0x04, 0x0f, 0x14, 0x0e, 0x05,
		    0x1e, 0x04));
	case '%':
		return (LIBG_FONT_PICK(row, 0x18, 0x19, 0x02, 0x04, 0x08,
		    0x13, 0x03));
	case '&':
		return (LIBG_FONT_PICK(row, 0x0c, 0x12, 0x14, 0x08, 0x15,
		    0x12, 0x0d));
	case '\'':
		return (LIBG_FONT_PICK(row, 0x04, 0x04, 0x08, 0x00, 0x00,
		    0x00, 0x00));
	case '(':
		return (LIBG_FONT_PICK(row, 0x02, 0x04, 0x08, 0x08, 0x08,
		    0x04, 0x02));
	case ')':
		return (LIBG_FONT_PICK(row, 0x08, 0x04, 0x02, 0x02, 0x02,
		    0x04, 0x08));
	case '*':
		return (LIBG_FONT_PICK(row, 0x00, 0x04, 0x15, 0x0e, 0x15,
		    0x04, 0x00));
	case '+':
		return (LIBG_FONT_PICK(row, 0x00, 0x04, 0x04, 0x1f, 0x04,
		    0x04, 0x00));
	case ',':
		return (LIBG_FONT_PICK(row, 0x00, 0x00, 0x00, 0x00, 0x04,
		    0x04, 0x08));
	case '-':
		return (LIBG_FONT_PICK(row, 0x00, 0x00, 0x00, 0x1f, 0x00,
		    0x00, 0x00));
	case '.':
		return (LIBG_FONT_PICK(row, 0x00, 0x00, 0x00, 0x00, 0x00,
		    0x0c, 0x0c));
	case '/':
		return (LIBG_FONT_PICK(row, 0x01, 0x02, 0x02, 0x04, 0x08,
		    0x08, 0x10));
	case '0':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x13, 0x15, 0x19,
		    0x11, 0x0e));
	case '1':
		return (LIBG_FONT_PICK(row, 0x04, 0x0c, 0x04, 0x04, 0x04,
		    0x04, 0x0e));
	case '2':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x01, 0x02, 0x04,
		    0x08, 0x1f));
	case '3':
		return (LIBG_FONT_PICK(row, 0x1e, 0x01, 0x01, 0x0e, 0x01,
		    0x01, 0x1e));
	case '4':
		return (LIBG_FONT_PICK(row, 0x02, 0x06, 0x0a, 0x12, 0x1f,
		    0x02, 0x02));
	case '5':
		return (LIBG_FONT_PICK(row, 0x1f, 0x10, 0x10, 0x1e, 0x01,
		    0x11, 0x0e));
	case '6':
		return (LIBG_FONT_PICK(row, 0x06, 0x08, 0x10, 0x1e, 0x11,
		    0x11, 0x0e));
	case '7':
		return (LIBG_FONT_PICK(row, 0x1f, 0x01, 0x02, 0x04, 0x08,
		    0x08, 0x08));
	case '8':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x11, 0x0e, 0x11,
		    0x11, 0x0e));
	case '9':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x11, 0x0f, 0x01,
		    0x02, 0x0c));
	case ':':
		return (LIBG_FONT_PICK(row, 0x00, 0x0c, 0x0c, 0x00, 0x0c,
		    0x0c, 0x00));
	case ';':
		return (LIBG_FONT_PICK(row, 0x00, 0x0c, 0x0c, 0x00, 0x04,
		    0x04, 0x08));
	case '<':
		return (LIBG_FONT_PICK(row, 0x02, 0x04, 0x08, 0x10, 0x08,
		    0x04, 0x02));
	case '=':
		return (LIBG_FONT_PICK(row, 0x00, 0x00, 0x1f, 0x00, 0x1f,
		    0x00, 0x00));
	case '>':
		return (LIBG_FONT_PICK(row, 0x08, 0x04, 0x02, 0x01, 0x02,
		    0x04, 0x08));
	case '?':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x01, 0x02, 0x04,
		    0x00, 0x04));
	case '@':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x17, 0x15, 0x17,
		    0x10, 0x0e));
	case 'A':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x11, 0x1f, 0x11,
		    0x11, 0x11));
	case 'B':
		return (LIBG_FONT_PICK(row, 0x1e, 0x11, 0x11, 0x1e, 0x11,
		    0x11, 0x1e));
	case 'C':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x10, 0x10, 0x10,
		    0x11, 0x0e));
	case 'D':
		return (LIBG_FONT_PICK(row, 0x1e, 0x11, 0x11, 0x11, 0x11,
		    0x11, 0x1e));
	case 'E':
		return (LIBG_FONT_PICK(row, 0x1f, 0x10, 0x10, 0x1e, 0x10,
		    0x10, 0x1f));
	case 'F':
		return (LIBG_FONT_PICK(row, 0x1f, 0x10, 0x10, 0x1e, 0x10,
		    0x10, 0x10));
	case 'G':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x10, 0x17, 0x11,
		    0x11, 0x0f));
	case 'H':
		return (LIBG_FONT_PICK(row, 0x11, 0x11, 0x11, 0x1f, 0x11,
		    0x11, 0x11));
	case 'I':
		return (LIBG_FONT_PICK(row, 0x0e, 0x04, 0x04, 0x04, 0x04,
		    0x04, 0x0e));
	case 'J':
		return (LIBG_FONT_PICK(row, 0x07, 0x02, 0x02, 0x02, 0x12,
		    0x12, 0x0c));
	case 'K':
		return (LIBG_FONT_PICK(row, 0x11, 0x12, 0x14, 0x18, 0x14,
		    0x12, 0x11));
	case 'L':
		return (LIBG_FONT_PICK(row, 0x10, 0x10, 0x10, 0x10, 0x10,
		    0x10, 0x1f));
	case 'M':
		return (LIBG_FONT_PICK(row, 0x11, 0x1b, 0x15, 0x15, 0x11,
		    0x11, 0x11));
	case 'N':
		return (LIBG_FONT_PICK(row, 0x11, 0x19, 0x15, 0x13, 0x11,
		    0x11, 0x11));
	case 'O':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x11, 0x11, 0x11,
		    0x11, 0x0e));
	case 'P':
		return (LIBG_FONT_PICK(row, 0x1e, 0x11, 0x11, 0x1e, 0x10,
		    0x10, 0x10));
	case 'Q':
		return (LIBG_FONT_PICK(row, 0x0e, 0x11, 0x11, 0x11, 0x15,
		    0x12, 0x0d));
	case 'R':
		return (LIBG_FONT_PICK(row, 0x1e, 0x11, 0x11, 0x1e, 0x14,
		    0x12, 0x11));
	case 'S':
		return (LIBG_FONT_PICK(row, 0x0f, 0x10, 0x10, 0x0e, 0x01,
		    0x01, 0x1e));
	case 'T':
		return (LIBG_FONT_PICK(row, 0x1f, 0x04, 0x04, 0x04, 0x04,
		    0x04, 0x04));
	case 'U':
		return (LIBG_FONT_PICK(row, 0x11, 0x11, 0x11, 0x11, 0x11,
		    0x11, 0x0e));
	case 'V':
		return (LIBG_FONT_PICK(row, 0x11, 0x11, 0x11, 0x11, 0x11,
		    0x0a, 0x04));
	case 'W':
		return (LIBG_FONT_PICK(row, 0x11, 0x11, 0x11, 0x15, 0x15,
		    0x15, 0x0a));
	case 'X':
		return (LIBG_FONT_PICK(row, 0x11, 0x11, 0x0a, 0x04, 0x0a,
		    0x11, 0x11));
	case 'Y':
		return (LIBG_FONT_PICK(row, 0x11, 0x11, 0x0a, 0x04, 0x04,
		    0x04, 0x04));
	case 'Z':
		return (LIBG_FONT_PICK(row, 0x1f, 0x01, 0x02, 0x04, 0x08,
		    0x10, 0x1f));
	case '[':
		return (LIBG_FONT_PICK(row, 0x0e, 0x08, 0x08, 0x08, 0x08,
		    0x08, 0x0e));
	case '\\':
		return (LIBG_FONT_PICK(row, 0x10, 0x08, 0x08, 0x04, 0x02,
		    0x02, 0x01));
	case ']':
		return (LIBG_FONT_PICK(row, 0x0e, 0x02, 0x02, 0x02, 0x02,
		    0x02, 0x0e));
	case '^':
		return (LIBG_FONT_PICK(row, 0x04, 0x0a, 0x11, 0x00, 0x00,
		    0x00, 0x00));
	case '_':
		return (LIBG_FONT_PICK(row, 0x00, 0x00, 0x00, 0x00, 0x00,
		    0x00, 0x1f));
	case '`':
		return (LIBG_FONT_PICK(row, 0x08, 0x04, 0x02, 0x00, 0x00,
		    0x00, 0x00));
	case '{':
		return (LIBG_FONT_PICK(row, 0x02, 0x04, 0x04, 0x18, 0x04,
		    0x04, 0x02));
	case '|':
		return (LIBG_FONT_PICK(row, 0x04, 0x04, 0x04, 0x00, 0x04,
		    0x04, 0x04));
	case '}':
		return (LIBG_FONT_PICK(row, 0x08, 0x04, 0x04, 0x03, 0x04,
		    0x04, 0x08));
	case '~':
		return (LIBG_FONT_PICK(row, 0x00, 0x08, 0x15, 0x02, 0x00,
		    0x00, 0x00));
	default:
		return (libg_font_row('?', row));
	}
}

#undef LIBG_FONT_PICK

#endif
